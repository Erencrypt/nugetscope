using System.Text;
using NugetScope.Core.Analysis;
using NugetScope.Core.Packages;
using NugetScope.Core.Scanning;
using NugetScope.Core.Unused;

namespace NugetScope.Core.Reporting;

/// <summary>
/// A Markdown report to read or share: summary counts, the gate result, one table per status and the problems.
/// GitHub-flavoured tables, so it renders in job summaries, pull request comments and most viewers.
/// </summary>
public static class MarkdownReportWriter
{
    /// <param name="unused">Result of the possibly-unused check, or null when it didn't run.</param>
    /// <param name="evaluation">The <c>--fail-on</c> result, when a gate was requested.</param>
    public static string Write(
        SolutionScan scan,
        IReadOnlyList<PackageSummary> packages,
        UnusedPackageReport? unused,
        FailureEvaluation? evaluation)
    {
        var report = new Report(scan, packages, unused);
        var md = new StringBuilder();

        md.AppendLine($"# NuGet packages: {scan.Solution.Name}").AppendLine();
        md.AppendLine($"{scan.Solution.Projects.Count} projects, {packages.Count} packages. Generated by nugetscope.").AppendLine();

        AppendSummary(md, report);
        AppendGate(md, evaluation);

        AppendSection(md, report, PackageStatus.Vulnerable,
            ["Package", "Version", "Severity", "Advisories", "Projects"],
            p => [Version(p, u => u.Vulnerabilities.Count > 0), Severity(p), Advisories(p), Projects(p, u => u.Vulnerabilities.Count > 0)]);

        AppendSection(md, report, PackageStatus.Deprecated,
            ["Package", "Version", "Reason", "Alternative", "Projects"],
            p => [Version(p, u => u.IsDeprecated), string.Join(", ", p.Deprecation!.Reasons), Alternative(p.Deprecation), Projects(p, u => u.IsDeprecated)]);

        AppendSection(md, report, PackageStatus.Outdated,
            ["Package", "Current", "Latest", "Projects"],
            p => [Version(p, u => u.IsOutdated), p.LatestVersion ?? "", Projects(p, u => u.IsOutdated)]);

        AppendSection(md, report, PackageStatus.Mismatch,
            ["Package", "Versions in use"],
            p => [string.Join("<br>", p.VersionGroups.Select(g => $"{g.Version}: {string.Join(", ", g.Projects.Select(x => x.Name))}"))]);

        AppendSection(md, report, PackageStatus.PossiblyUnused,
            ["Package", "Projects"],
            p => [Projects(p, u => u.IsPossiblyUnused)],
            note: "None of these packages' namespaces appear in the listed projects' source, markup or config files. " +
                "This is a hint, not an issue: a package can still be needed without being named there, for example " +
                "when it is loaded through reflection or DI assembly scanning, or referenced only by assembly name in configuration. " +
                "Check before removing a package.");

        AppendProblems(md, scan.Packages, unused);

        return md.ToString();
    }

    private static void AppendSummary(StringBuilder md, Report report)
    {
        PackageStatus[] statuses = [.. PackageStatusNames.Each(PackageStatusNames.AnyIssue), PackageStatus.PossiblyUnused];

        AppendRow(md, [.. statuses.Select(Heading)]);
        md.AppendLine($"|{string.Concat(statuses.Select(_ => " ---: |"))}");
        AppendRow(md, [.. statuses.Select(s => report.IsChecked(s) ? report.Flagged(s).Count.ToString() : "?")]);
        md.AppendLine();

        if (statuses.Any(s => !report.IsChecked(s)))
        {
            md.AppendLine("`?` means the check didn't run, so the count is unknown (see Problems).").AppendLine();
        }
    }

    private static void AppendGate(StringBuilder md, FailureEvaluation? evaluation)
    {
        if (evaluation is null)
        {
            return;
        }

        md.AppendLine($"> **{Escape(evaluation.Describe())}**");
        foreach (string gap in evaluation.Gaps)
        {
            md.AppendLine(">").AppendLine($"> {Escape(gap)}");
        }

        md.AppendLine();
    }

    private static void AppendSection(
        StringBuilder md,
        Report report,
        PackageStatus status,
        string[] headers,
        Func<PackageSummary, string[]> cells,
        string? note = null)
    {
        if (!report.IsChecked(status))
        {
            md.AppendLine($"## {Heading(status)}").AppendLine().AppendLine("_Not checked._").AppendLine();
            return;
        }

        IReadOnlyList<PackageSummary> flagged = report.Flagged(status);
        if (flagged.Count == 0)
        {
            return;
        }

        md.AppendLine($"## {Heading(status)} ({flagged.Count})").AppendLine();
        if (note is not null)
        {
            md.AppendLine($"_{note}_").AppendLine();
        }

        AppendRow(md, headers);
        md.AppendLine($"|{string.Concat(headers.Select(_ => " --- |"))}");
        foreach (PackageSummary package in flagged)
        {
            AppendRow(md, [PackageName(package), .. cells(package)]);
        }

        md.AppendLine();
    }

    private static void AppendProblems(StringBuilder md, PackageScanResult scan, UnusedPackageReport? unused)
    {
        var problems = scan.Problems.Select(p => ("Solution", p))
            .Concat(scan.Projects.SelectMany(project => project.Problems.Select(p => (project.Project.Name, p))))
            .ToList();
        var skipped = unused?.Skipped.OrderBy(s => s.Key.Name, StringComparer.OrdinalIgnoreCase).ToList() ?? [];

        if (problems.Count == 0 && skipped.Count == 0)
        {
            return;
        }

        md.AppendLine($"## Problems ({problems.Count + skipped.Count})").AppendLine();
        AppendRow(md, ["Level", "Where", "Code", "Message"]);
        md.AppendLine("| --- | --- | --- | --- |");

        foreach ((string scope, PackageProblem problem) in problems)
        {
            AppendRow(md, [problem.Level.ToString().ToLowerInvariant(), scope, problem.Code ?? "", problem.Message]);
        }

        foreach ((var project, string reason) in skipped)
        {
            AppendRow(md, ["info", project.Name, "", $"Not checked for unused packages: {reason}"]);
        }

        md.AppendLine();
    }

    private static string Heading(PackageStatus status) => status switch
    {
        PackageStatus.Vulnerable => "Vulnerable",
        PackageStatus.Deprecated => "Deprecated",
        PackageStatus.Outdated => "Outdated",
        PackageStatus.Mismatch => "Version mismatch",
        PackageStatus.PossiblyUnused => "Possibly unused",
        _ => status.ToString(),
    };

    private static string PackageName(PackageSummary package) =>
        $"`{package.Id}`{(package.IsTransitiveOnly ? " (transitive)" : "")}";

    private static string Version(PackageSummary package, Func<PackageUsage, bool> affected) =>
        string.Join(", ", package.Usages.Where(affected).Select(u => u.ResolvedVersion).OfType<string>()
            .Distinct(StringComparer.OrdinalIgnoreCase).Order(VersionStringComparer.Instance));

    private static string Projects(PackageSummary package, Func<PackageUsage, bool> affected) =>
        string.Join(", ", package.Usages.Where(affected).Select(u => u.Project.Name).Distinct());

    private static string Severity(PackageSummary package) => package.HighestSeverity?.ToString().ToLowerInvariant() ?? "";

    // The advisory id (last URL segment, e.g. GHSA-xxxx) keeps the column narrow.
    private static string Advisories(PackageSummary package) => string.Join(", ", package.Vulnerabilities
        .Select(v => v.AdvisoryUrl)
        .OfType<Uri>()
        .Distinct()
        .Select(url => $"[{url.Segments[^1].Trim('/')}]({url})"));

    private static string Alternative(PackageDeprecation deprecation) => deprecation.AlternativePackageId is { } id
        ? $"`{id}`{(deprecation.AlternativeVersionRange is { } range ? $" {range}" : "")}"
        : "";

    private static void AppendRow(StringBuilder md, IEnumerable<string> cells) =>
        md.AppendLine($"| {string.Join(" | ", cells.Select(EscapeCell))} |");

    // Pipes would end the cell and newlines the row; <br> (from the mismatch column) is kept.
    private static string EscapeCell(string text) => text.Replace("|", "\\|").ReplaceLineEndings(" ");

    private static string Escape(string text) => text.ReplaceLineEndings(" ");

    private sealed class Report(SolutionScan scan, IReadOnlyList<PackageSummary> packages, UnusedPackageReport? unused)
    {
        public bool IsChecked(PackageStatus status)
        {
            if (status == PackageStatus.PossiblyUnused)
            {
                return unused is not null;
            }

            PackageChecks check = PackageStatusNames.RequiredCheck(status);
            return check == PackageChecks.None || scan.Packages.CompletedChecks.HasFlag(check);
        }

        public IReadOnlyList<PackageSummary> Flagged(PackageStatus status) =>
            [.. packages.Where(p => p.Status.HasFlag(status)).OrderBy(p => p.Id, StringComparer.OrdinalIgnoreCase)];
    }
}
